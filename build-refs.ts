// Encodes reference/*.md into refs-data.js as window.STUDIO_REFS.
// Run once after editing any reference doc:  node build-refs.ts
// Node runs TypeScript directly (>= 22.18 strips types), so this needs no build step.
import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { join } from "node:path";

const here: string = import.meta.dirname;
const dir = join(here, "reference");
const files = readdirSync(dir).filter((f) => f.endsWith(".md"));

const refs: Record<string, string> = {};
for (const f of files) {
  const id = f.replace(/\.md$/, "");
  // Normalize to LF so the generated file is byte-identical on every platform,
  // whatever line endings the working copy was checked out with.
  refs[id] = readFileSync(join(dir, f), "utf8").split("\r\n").join("\n");
}

const out = `// AUTO-GENERATED by build-refs.ts — do not edit by hand.
window.STUDIO_REFS = ${JSON.stringify(refs, null, 2)};
`;
writeFileSync(join(here, "refs-data.js"), out, "utf8");
console.log(
  "Wrote refs-data.js with",
  Object.keys(refs).length,
  "reference docs:",
  Object.keys(refs).join(", "),
);
